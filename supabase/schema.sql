-- Ballet AI Coach — database setup
-- Run once: Supabase dashboard → SQL Editor → New query → paste everything → Run.
-- Every row belongs to the signed-in account (owner). Row-level security means each
-- family can only see and change its own dancers, sessions, tendus and keyframes.

-- Dancers (the children practicing)
create table if not exists public.dancers (
  id          uuid primary key default gen_random_uuid(),
  owner       uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name        text not null check (char_length(name) between 1 and 60),
  schedule    jsonb not null default '[]'::jsonb,       -- regular class days, 0 = Sunday … 6 = Saturday
  created_at  timestamptz not null default now()
);

-- Practice sessions (one per "Reset" / page visit)
create table if not exists public.sessions (
  id          uuid primary key,                        -- generated by the app
  owner       uuid not null default auth.uid() references auth.users(id) on delete cascade,
  dancer_id   uuid not null references public.dancers(id) on delete cascade,
  module      text not null default 'tendu',            -- tendu / plie
  started_at  timestamptz not null,
  ended_at    timestamptz,
  total       int not null default 0,                  -- tendus in the session
  good        int not null default 0,                  -- tendus with every check correct
  summary     jsonb not null default '{}'::jsonb,      -- per direction / per check counts
  created_at  timestamptz not null default now()
);

-- One row per tendu
create table if not exists public.reps (
  id           uuid primary key,                       -- generated by the app
  owner        uuid not null default auth.uid() references auth.users(id) on delete cascade,
  session_id   uuid not null references public.sessions(id) on delete cascade,
  dancer_id    uuid not null references public.dancers(id) on delete cascade,
  module       text not null default 'tendu',          -- tendu / plie
  n            int not null,                           -- rep number within the session
  at           timestamptz not null,
  direction    text,                                   -- tendu: devant / seconde / derriere; plié: first-demi, second-grand, …
  side         text,                                   -- left / right (working leg)
  all_correct  boolean not null,
  errors       text[] not null default '{}',           -- check keys that failed
  measured     text[] not null default '{}',           -- check keys that could be measured
  results      jsonb,                                  -- per check: [state, message key, value]
  segs         jsonb,                                  -- foot-phase timeline
  peak         real,                                   -- where the farthest point falls on the timeline (0-1)
  keyframes    jsonb,                                  -- storage paths: start / far / close
  coords       jsonb,                                  -- leg landmark coordinates for every frame of the tendu
  created_at   timestamptz not null default now()
);

create index if not exists sessions_dancer_started on public.sessions (dancer_id, started_at);
create index if not exists sessions_dancer_module on public.sessions (dancer_id, module, started_at);
create index if not exists reps_session on public.reps (session_id, n);

-- Row-level security: only the owner can read or write
alter table public.dancers  enable row level security;
alter table public.sessions enable row level security;
alter table public.reps     enable row level security;

create policy "own dancers" on public.dancers
  for all to authenticated
  using (owner = (select auth.uid()))
  with check (owner = (select auth.uid()));

create policy "own sessions" on public.sessions
  for all to authenticated
  using (owner = (select auth.uid()))
  with check (owner = (select auth.uid())
              and exists (select 1 from public.dancers d where d.id = dancer_id and d.owner = (select auth.uid())));

create policy "own reps" on public.reps
  for all to authenticated
  using (owner = (select auth.uid()))
  with check (owner = (select auth.uid())
              and exists (select 1 from public.sessions s where s.id = session_id and s.owner = (select auth.uid())));

-- Pain diary: one entry per dancer per day
create table if not exists public.diary (
  id          uuid primary key default gen_random_uuid(),
  owner       uuid not null default auth.uid() references auth.users(id) on delete cascade,
  dancer_id   uuid not null references public.dancers(id) on delete cascade,
  day         date not null,
  pain        smallint not null check (pain between 0 and 5),
  areas       text[] not null default '{}',       -- heel_L, knee_R, …
  activities  text[] not null default '{}',       -- class, home, rehearsal, rest
  note        text check (note is null or char_length(note) <= 500),
  updated_at  timestamptz not null default now(),
  unique (dancer_id, day)
);
alter table public.diary enable row level security;

do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'diary' and policyname = 'own diary') then
    create policy "own diary" on public.diary
      for all to authenticated
      using (owner = (select auth.uid()))
      with check (owner = (select auth.uid())
                  and exists (select 1 from public.dancers d where d.id = dancer_id and d.owner = (select auth.uid())));
  end if;
end $$;

-- Private bucket for keyframe pictures; files live under <user id>/...
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('keyframes', 'keyframes', false, 1048576, array['image/jpeg'])
on conflict (id) do nothing;

create policy "own keyframes read" on storage.objects
  for select to authenticated
  using (bucket_id = 'keyframes' and (storage.foldername(name))[1] = (select auth.uid())::text);

create policy "own keyframes upload" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'keyframes' and (storage.foldername(name))[1] = (select auth.uid())::text);

create policy "own keyframes update" on storage.objects
  for update to authenticated
  using (bucket_id = 'keyframes' and (storage.foldername(name))[1] = (select auth.uid())::text);

create policy "own keyframes delete" on storage.objects
  for delete to authenticated
  using (bucket_id = 'keyframes' and (storage.foldername(name))[1] = (select auth.uid())::text);
